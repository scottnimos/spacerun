// Builds Assets/AppIcon.png (macOS icon shape) from Assets/icon-source.png,
// then embeds it as Sources/SpaceRun/AppIconData.swift.
// Run from the repo root: swift scripts/make-icon.swift
import AppKit

let size = 512.0
let inset = size * 100 / 1024          // Apple icon grid: 824/1024 body, centred.
let body = NSRect(x: inset, y: inset, width: size - 2 * inset, height: size - 2 * inset)
let radius = body.width * 0.225

guard let source = NSImage(contentsOfFile: "Assets/icon-source.png") else { fatalError("Missing Assets/icon-source.png") }
let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: Int(size), pixelsHigh: Int(size), bitsPerSample: 8,
                           samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB,
                           bytesPerRow: 0, bitsPerPixel: 0)!
NSGraphicsContext.saveGraphicsState()
NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: rep)
NSGraphicsContext.current?.imageInterpolation = .high
let shape = NSBezierPath(roundedRect: body, xRadius: radius, yRadius: radius)
shape.addClip()
NSColor.black.setFill()
body.fill()
// Fill the height and centre horizontally; the picture's own edges are black.
let scale = body.height / source.size.height
var drawn = NSRect(x: 0, y: body.minY, width: source.size.width * scale, height: body.height)
drawn.origin.x = body.midX - drawn.width / 2
source.draw(in: drawn)
NSGraphicsContext.restoreGraphicsState()

let png = rep.representation(using: .png, properties: [:])!
try! png.write(to: URL(fileURLWithPath: "Assets/AppIcon.png"))
let swift = """
// Generated by scripts/make-icon.swift from Assets/AppIcon.png. Do not edit.
import Foundation

enum AppIconData {
    static let png = Data(base64Encoded: "\(png.base64EncodedString())")!
}

"""
try! swift.write(toFile: "Sources/SpaceRun/AppIconData.swift", atomically: true, encoding: .utf8)
print("Wrote Assets/AppIcon.png (\(png.count) bytes) and Sources/SpaceRun/AppIconData.swift")
